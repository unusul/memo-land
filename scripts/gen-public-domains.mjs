// Generates the public-domains migration from the public domain list in @attivita/core, so the server and
// the app never disagree on which email domains form a domain group.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const source = readFileSync(join(root, 'packages/core/src/public-domains.ts'), 'utf8');
const start = source.indexOf('= [');
const list = source.slice(start, source.indexOf('];', start) + 1);
const domains = [...list.matchAll(/'([^']+)'/g)].map(m => m[1]);
if (domains.length === 0) throw new Error('no public domains found in public-domains.ts');

const values = domains.map(d => `  ('${d.replace(/'/g, "''")}')`).join(',\n');
writeFileSync(join(root, 'supabase/migrations/0005_public_domains.sql'),
  `-- Generated by scripts/gen-public-domains.mjs from packages/core/src/public-domains.ts. Do not edit.\n` +
  `insert into public.public_domains (domain) values\n${values}\non conflict do nothing;\n`);
console.log(`0005_public_domains.sql: ${domains.length} public domains`);
