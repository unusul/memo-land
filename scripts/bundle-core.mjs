// The core in one file for the Edge Functions (2026-11-19): they run on Deno, which does not read the core as it is
// (imports written `.js` for `.ts` files, `rrule` from npm). esbuild comes with Vite; the file is rebuilt before each
// deploy and kept out of git.
import { build } from 'esbuild';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('..', import.meta.url));

await build({
  entryPoints: [`${root}packages/core/src/index.ts`],
  outfile: `${root}supabase/functions/_shared/core.js`,
  bundle: true,
  format: 'esm',
  platform: 'neutral',
  target: 'es2022',
  mainFields: ['module', 'main'],
  banner: { js: '// Generated by scripts/bundle-core.mjs from packages/core: do not edit.' },
  logLevel: 'info',
});
